//! Configuration for Aftermath (`aftermath.toml`).
//!
//! Configuration is read-only with respect to the repository: loading config
//! never writes anything, and the effective configuration is echoed (redacted)
//! into reports for reproducibility.

use std::path::{Path, PathBuf};

use serde::{Deserialize, Serialize};

/// Top-level configuration file structure.
#[derive(Clone, Debug, PartialEq, Serialize, Deserialize, Default)]
#[serde(default, deny_unknown_fields)]
pub struct Config {
    pub analysis: AnalysisConfig,
    pub tests: TestsConfig,
    pub history: HistoryConfig,
    pub cache: CacheConfig,
    pub witness: WitnessConfig,
}

#[derive(Clone, Debug, PartialEq, Serialize, Deserialize)]
#[serde(default, deny_unknown_fields)]
pub struct AnalysisConfig {
    /// Maximum transitive traversal depth (bounded on purpose).
    pub depth: u32,
    /// Files larger than this are skipped and reported as a blind spot.
    pub max_file_bytes: u64,
    /// Extensions considered analyzable source.
    pub include_extensions: Vec<String>,
    /// Glob-ish directory/file exclusion patterns (`**` supported, matched
    /// against repository-relative paths).
    pub exclude: Vec<String>,
    /// Markers that identify generated files (first 4 KiB scanned).
    pub generated_markers: Vec<String>,
}

impl Default for AnalysisConfig {
    fn default() -> Self {
        Self {
            depth: 3,
            max_file_bytes: 1_048_576,
            include_extensions: vec![
                "js".into(),
                "jsx".into(),
                "mjs".into(),
                "cjs".into(),
                "ts".into(),
                "tsx".into(),
            ],
            exclude: vec![
                "node_modules/**".into(),
                "dist/**".into(),
                "build/**".into(),
                "out/**".into(),
                "coverage/**".into(),
                ".git/**".into(),
                "**/*.min.js".into(),
                "**/*.d.ts".into(),
            ],
            generated_markers: vec![
                "@generated".into(),
                "Code generated by".into(),
                "DO NOT EDIT".into(),
            ],
        }
    }
}

#[derive(Clone, Debug, PartialEq, Serialize, Deserialize)]
#[serde(default, deny_unknown_fields)]
pub struct TestsConfig {
    /// Patterns identifying test files (matched against repository-relative paths).
    pub patterns: Vec<String>,
    /// Explicit test command as an argv array. When empty, `package.json`
    /// `scripts.test` is used if present.
    pub command: Vec<String>,
    /// Extensions treated as test files.
    pub extensions: Vec<String>,
}

impl Default for TestsConfig {
    fn default() -> Self {
        Self {
            patterns: vec![
                "**/*.test.*".into(),
                "**/*.spec.*".into(),
                "**/__tests__/**".into(),
            ],
            command: vec![],
            extensions: vec![
                "js".into(),
                "jsx".into(),
                "mjs".into(),
                "cjs".into(),
                "ts".into(),
                "tsx".into(),
            ],
        }
    }
}

#[derive(Clone, Debug, PartialEq, Serialize, Deserialize)]
#[serde(default, deny_unknown_fields)]
pub struct HistoryConfig {
    /// History analysis is opt-in (Feature F is optional by design).
    pub enabled: bool,
    /// Maximum number of commits examined.
    pub limit: u32,
    /// Minimum shared commits before a co-change pair is reported.
    pub co_change_threshold: u32,
}

impl Default for HistoryConfig {
    fn default() -> Self {
        Self {
            enabled: false,
            limit: 200,
            co_change_threshold: 2,
        }
    }
}

#[derive(Clone, Debug, PartialEq, Serialize, Deserialize)]
#[serde(default, deny_unknown_fields)]
pub struct CacheConfig {
    /// Content-hash based parse cache (`.aftermath/cache.json`).
    pub enabled: bool,
}

impl Default for CacheConfig {
    fn default() -> Self {
        Self { enabled: true }
    }
}

#[derive(Clone, Debug, PartialEq, Serialize, Deserialize)]
#[serde(default, deny_unknown_fields)]
pub struct WitnessConfig {
    /// `advisory` never blocks a commit; `blocking` exits nonzero on
    /// blocking conditions defined by the hook policy.
    pub policy: WitnessPolicy,
}

impl Default for WitnessConfig {
    fn default() -> Self {
        Self {
            policy: WitnessPolicy::Advisory,
        }
    }
}

#[derive(Clone, Copy, Debug, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum WitnessPolicy {
    Advisory,
    Blocking,
}

impl Config {
    /// Load configuration from `path`, or return defaults when it does not exist.
    pub fn load(path: &Path) -> Result<Self, ConfigError> {
        let text = match std::fs::read_to_string(path) {
            Ok(t) => t,
            Err(e) if e.kind() == std::io::ErrorKind::NotFound => return Ok(Self::default()),
            Err(e) => return Err(ConfigError::Io(path.display().to_string(), e)),
        };
        let cfg: Config = toml::from_str(&text).map_err(|e| ConfigError::Parse(e.to_string()))?;
        Ok(cfg)
    }

    /// Serialize the default configuration as TOML (used by `aftermath init`).
    pub fn to_toml(&self) -> String {
        let mut out = String::new();
        out.push_str(
            "# Aftermath configuration — every value is optional; this file is read-only\n",
        );
        out.push_str("# with respect to your source code.\n\n");

        out.push_str("[analysis]\n");
        out.push_str(&format!("depth = {}\n", self.analysis.depth));
        out.push_str(&format!(
            "max_file_bytes = {}\n",
            self.analysis.max_file_bytes
        ));
        out.push_str(&format!(
            "include_extensions = [{}]\n",
            join_toml_array(&self.analysis.include_extensions)
        ));
        out.push_str(&format!(
            "exclude = [{}]\n",
            join_toml_array(&self.analysis.exclude)
        ));
        out.push_str(&format!(
            "generated_markers = [{}]\n\n",
            join_toml_array(&self.analysis.generated_markers)
        ));

        out.push_str("[tests]\n");
        out.push_str(&format!(
            "patterns = [{}]\n",
            join_toml_array(&self.tests.patterns)
        ));
        out.push_str(&format!(
            "command = [{}]\n\n",
            join_toml_array(&self.tests.command)
        ));

        out.push_str("[history]\n");
        out.push_str(&format!("enabled = {}\n", self.history.enabled));
        out.push_str(&format!("limit = {}\n", self.history.limit));
        out.push_str(&format!(
            "co_change_threshold = {}\n\n",
            self.history.co_change_threshold
        ));

        out.push_str("[cache]\n");
        out.push_str(&format!("enabled = {}\n\n", self.cache.enabled));

        out.push_str("[witness]\n");
        let policy = match self.witness.policy {
            WitnessPolicy::Advisory => "advisory",
            WitnessPolicy::Blocking => "blocking",
        };
        out.push_str(&format!("policy = \"{}\"\n", policy));
        out
    }

    /// Machine-independent summary embedded into reports.
    pub fn summary_value(&self) -> serde_json::Value {
        serde_json::json!({
            "depth": self.analysis.depth,
            "max_file_bytes": self.analysis.max_file_bytes,
            "include_extensions": self.analysis.include_extensions,
            "exclude": self.analysis.exclude,
            "test_patterns": self.tests.patterns,
            "test_command": self.tests.command,
            "history_enabled": self.history.enabled,
            "history_limit": self.history.limit,
            "cache_enabled": self.cache.enabled,
            "witness_policy": match self.witness.policy {
                WitnessPolicy::Advisory => "advisory",
                WitnessPolicy::Blocking => "blocking",
            },
        })
    }

    /// Standard location of the configuration file inside a repository.
    pub fn file_name() -> &'static str {
        "aftermath.toml"
    }

    pub fn find(repo_root: &Path) -> PathBuf {
        repo_root.join(Self::file_name())
    }
}

fn join_toml_array(items: &[String]) -> String {
    items
        .iter()
        .map(|s| format!("\"{}\"", s.replace('\\', "\\\\").replace('"', "\\\"")))
        .collect::<Vec<_>>()
        .join(", ")
}

#[derive(Debug, thiserror::Error)]
pub enum ConfigError {
    #[error("failed to read config {0}: {1}")]
    Io(String, std::io::Error),
    #[error("invalid configuration: {0}")]
    Parse(String),
}

/// Whether a repository-relative path is covered by any exclude pattern.
///
/// Used both while walking the tree and to drop excluded files from a change
/// set. `dir/**` patterns cover every nested file because `**` spans segments.
pub fn path_excluded(path: &str, exclude: &[String]) -> bool {
    exclude.iter().any(|p| glob_match(p, path))
}

/// Minimal `**` glob matcher for path patterns (no external crate).
///
/// Supports `**` (any number of path segments), `*` (within a segment) and
/// exact segments. Matching is done on repository-relative `/`-separated paths.
pub fn glob_match(pattern: &str, path: &str) -> bool {
    let p: Vec<&str> = pattern.split('/').collect();
    let t: Vec<&str> = path.split('/').collect();
    match_segments(&p, &t)
}

fn match_segments(pattern: &[&str], path: &[&str]) -> bool {
    if pattern.is_empty() {
        return path.is_empty();
    }
    let head = pattern[0];
    if head == "**" {
        // `**` matches zero or more segments.
        for skip in 0..=path.len() {
            if match_segments(&pattern[1..], &path[skip..]) {
                return true;
            }
        }
        return false;
    }
    if path.is_empty() {
        return false;
    }
    if !segment_match(head, path[0]) {
        return false;
    }
    match_segments(&pattern[1..], &path[1..])
}

fn segment_match(pattern: &str, seg: &str) -> bool {
    if pattern == "*" {
        return !seg.contains('/');
    }
    let p: Vec<char> = pattern.chars().collect();
    let s: Vec<char> = seg.chars().collect();
    // Iterative wildcard match with backtracking. Neither `*` nor `?` may
    // cross a `/`: they operate *within* a single path segment.
    let (mut pi, mut si) = (0usize, 0usize);
    let (mut star, mut mark) = (None, 0usize);
    while si < s.len() {
        // Literal char always matches; `?` matches any single char but `/`.
        if pi < p.len() && (p[pi] == s[si] || (p[pi] == '?' && s[si] != '/')) {
            pi += 1;
            si += 1;
        } else if pi < p.len() && p[pi] == '*' {
            star = Some(pi);
            mark = si;
            pi += 1;
        } else if let Some(st) = star {
            if s[mark] == '/' {
                return false; // a `*` cannot match across a segment boundary
            }
            pi = st + 1;
            mark += 1;
            si = mark;
        } else {
            return false;
        }
    }
    while pi < p.len() && p[pi] == '*' {
        pi += 1;
    }
    pi == p.len()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn glob_double_star_matches_any_depth() {
        assert!(glob_match("node_modules/**", "node_modules/pkg/index.js"));
        assert!(glob_match("**/*.test.ts", "a/b/c.test.ts"));
        assert!(glob_match("**/*.min.js", "dist/x.min.js"));
        assert!(!glob_match("src/**", "lib/x.ts"));
        assert!(glob_match("src/**", "src/a/b.ts"));
    }

    #[test]
    fn glob_star_stays_within_segment() {
        assert!(segment_match("*.ts", "app.ts"));
        assert!(!segment_match("*.ts", "a/b.ts"));
        assert!(segment_match("test_*.js", "test_one.js"));
    }

    #[test]
    fn defaults_are_sane() {
        let c = Config::default();
        assert_eq!(c.analysis.depth, 3);
        assert_eq!(c.witness.policy, WitnessPolicy::Advisory);
        assert!(!c.history.enabled, "history must be opt-in");
        assert!(!c.tests.command.contains(&"rm".to_string()));
    }

    #[test]
    fn toml_round_trip() {
        let c = Config::default();
        let text = c.to_toml();
        let back: Config = toml::from_str(&text).expect("generated TOML must parse");
        assert_eq!(back, c);
    }

    #[test]
    fn unknown_keys_are_rejected() {
        let err = toml::from_str::<Config>("[analysis]\ndepth = 2\nbogus = 1\n");
        assert!(
            err.is_err(),
            "unknown keys must be rejected (malicious config defense)"
        );
    }

    #[test]
    fn load_missing_file_returns_defaults() {
        let dir = std::env::temp_dir().join("aftermath-missing-config-test");
        let cfg = Config::load(&dir.join("nope.toml")).unwrap();
        assert_eq!(cfg, Config::default());
    }
}
